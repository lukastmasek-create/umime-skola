export function getTeamsText(locale: Locale): TeamsText {
  return texts[locale] ?? texts.cs;
}

export function tfill(template: string, ...args: (string | number)[]): string {
  return template.replace(/\{(\d+)\}/g, (_, i) => String(args[Number(i)] ?? ""));
}

