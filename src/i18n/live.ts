/** Dosadí {klíče} do textu: fmt("Ahoj {name}", { name: "Anna" }). */
export function fmt(text: string, values: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (_, k: string) => String(values[k] ?? ""));
}
