"""Assemble src/*.lua into a single Roblox Studio command-bar installer (install.lua).

Usage (from roblox/economy):  python3 tools/build.py
Paste install.lua into Studio's command bar (View > Command Bar) and press Enter.
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "src"

# (class, name, parent variable, source file) in creation order. Parents must exist before children.
LAYOUT = [
    ("ModuleScript", "Config", "econ", "Config.lua"),
    ("ModuleScript", "Logic", "econ", "Logic.lua"),
    ("ModuleScript", "Strings", "econ", "Strings.lua"),
    ("Script", "EconomyService", "SSS", "EconomyService.server.lua", "svc"),
    ("ModuleScript", "ServerCore", "svc", "ServerCore.lua"),
    ("LocalScript", "EconomyUI", "SPS", "EconomyUI.client.lua", "ui"),
    ("ModuleScript", "Theme", "ui", "Theme.lua"),
    ("ModuleScript", "Widgets", "ui", "Widgets.lua"),
    ("ModuleScript", "Screens", "ui", "Screens.lua"),
]

HEADER = """-- Tycoon Life installer (generated by tools/build.py - edit src/, not this file).
local RS = game:GetService("ReplicatedStorage")
local SSS = game:GetService("ServerScriptService")
local SPS = game:GetService("StarterPlayer"):WaitForChild("StarterPlayerScripts")
local function clear(p, n) local o = p:FindFirstChild(n) if o then o:Destroy() end end
clear(RS, "Economy") clear(SSS, "EconomyService") clear(SPS, "EconomyUI")
local function make(class, name, parent, source)
	local o = Instance.new(class) o.Name = name o.Source = source o.Parent = parent return o
end
local econ = Instance.new("Folder") econ.Name = "Economy" econ.Parent = RS
"""

FOOTER = 'print("Tycoon Life installed. Enable Studio Access to API Services (Game Settings > Security) so progress saves, then press Play.")\n'


def main():
    out = [HEADER]
    for entry in LAYOUT:
        cls, name, parent, file = entry[:4]
        var = entry[4] if len(entry) > 4 else None
        body = (SRC / file).read_text(encoding="utf-8")
        if "]==]" in body:
            raise SystemExit(f"{file} contains the long-string terminator ]==]")
        if not body.endswith("\n"):
            body += "\n"
        prefix = f"local {var} = " if var else ""
        out.append(f'{prefix}make("{cls}", "{name}", {parent}, [==[\n{body}]==])\n')
    out.append(FOOTER)
    target = ROOT / "install.lua"
    target.write_text("".join(out), encoding="utf-8")
    print(f"wrote {target.relative_to(ROOT)} ({target.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
